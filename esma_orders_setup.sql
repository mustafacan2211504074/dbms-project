-- 4. KARIŞIK İŞLEMLER İÇİN PL/SQL SİPARİŞ PROSEDÜRÜ
create or replace procedure processcheckout (
   p_customer_id in number,
   p_shop_id     in number,
   p_product_id  in number,
   p_quantity    in number,
   p_unit_price  in number
) as
   v_new_order_id number;
   v_total_price  number;
begin
   v_total_price := p_quantity * p_unit_price;
   insert into orders (
      customer_id,
      shop_id,
      total_price,
      status
   ) values ( p_customer_id,
              p_shop_id,
              v_total_price,
              'PREPARING' ) returning order_id into v_new_order_id;

   insert into orderdetails (
      order_id,
      product_id,
      quantity,
      unit_price
   ) values ( v_new_order_id,
              p_product_id,
              p_quantity,
              p_unit_price );

   commit;
   dbms_output.put_line('Sipariş Onaylandı! ID: ' || v_new_order_id);
exception
   when others then
      rollback;
      dbms_output.put_line('Hata oluştu, işlem geri alındı: ' || sqlerrm);
end processcheckout;
/

-- 5. HOCAYA GÖSTERİLECEK ÖRNEK SORGULAMA (ŞOV KISMI)
-- En çok sipariş alan ve 500 TL üzeri ciro yapan mağazalar:
select s.name as magaza_adi,
       count(distinct o.order_id) as toplam_siparis,
       sum(od.quantity * od.unit_price) as toplam_ciro
  from shop s
  join orders o
on s.shop_id = o.shop_id
  join orderdetails od
on o.order_id = od.order_id
 group by s.name
having sum(od.quantity * od.unit_price) > 500
 order by toplam_ciro desc;