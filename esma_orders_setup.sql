-- 1. SİPARİŞ TABLOLARINI OLUŞTURMA (DDL)
create table orders (
   order_id    number generated by default as identity primary key,
   customer_id number not null,
   shop_id     number not null,
   courier_id  number,
   coupon_id   number,
   total_price number(10,2) default 0,
   status      varchar2(20) default 'PENDING',
   order_date  timestamp default current_timestamp,
   constraint fk_ord_cust foreign key ( customer_id )
      references users ( user_id ),
   constraint fk_ord_shop foreign key ( shop_id )
      references shop ( shop_id ),
   constraint fk_ord_cour foreign key ( courier_id )
      references users ( user_id ),
   constraint fk_ord_coup foreign key ( coupon_id )
      references coupons ( id )
);

create table orderdetails (
   detail_id  number generated by default as identity primary key,
   order_id   number not null,
   product_id number not null,
   quantity   number not null,
   unit_price number(10,2) not null,
   constraint fk_det_order foreign key ( order_id )
      references orders ( order_id )
         on delete cascade,
   constraint fk_det_prod foreign key ( product_id )
      references products ( product_id )
);

